int main ()
{
	for (const auto & vector : vectors64)
	{
		uint8_t digest[8] = { };
		i2p::crypto::Siphash<8> (digest, message, vector.length, key);
		assert (std::memcmp (digest, vector.digest, sizeof (digest)) == 0);
	}

	for (const auto & vector : vectors128)
	{
		uint8_t digest[16] = { };
		i2p::crypto::Siphash<16> (digest, message, vector.length, key);
		assert (std::memcmp (digest, vector.digest, sizeof (digest)) == 0);
	}

	// The NTCP2 caller hashes an IV in place. Ensure the rewrite reads the
	// complete input before writing either output word.
	uint8_t inPlace[16] = { };
	std::memcpy (inPlace, message, sizeof (inPlace));
	uint8_t expected[16] = { };
	i2p::crypto::Siphash<16> (expected, message, sizeof (inPlace), key);
	i2p::crypto::Siphash<16> (inPlace, inPlace, sizeof (inPlace), key);
	assert (std::memcmp (inPlace, expected, sizeof (inPlace)) == 0);
}

